#include <math.h>
#include <stdint.h>
#include <stdio.h>

static float hash(int i, int seed) {
	uint32_t h = (uint32_t)i * 374761393u + (uint32_t)seed * 668265263u;
	h = (h ^ (h >> 13)) * 1274126177u;
	h ^= h >> 16;
	return ((float)h / (float)UINT32_MAX) * 2.0f - 1.0f;
}
static float clamp01(float t) { return t < 0 ? 0 : t > 1 ? 1 : t; }
static float smootherstep(float t) { return t * t * t * (t * (t * 6.0f - 15.0f) + 10.0f); }
static float signed_noise(float x, int seed) {
	int i = (int)floorf(x);
	float f = x - (float)i;
	float t = smootherstep(f);
	float a = hash(i, seed), b = hash(i + 1, seed);
	return a + (b - a) * clamp01(t);
}
static float fractal(float x, int seed, int octaves, float spread) {
	float sum = 0, norm = 0, amp = 1, freq = 1;
	for (int o = 0; o < octaves; o++) {
		float detune = 1.0f + spread * (hash(o * 71 + 13, seed) * 0.5f);
		sum += signed_noise(x * freq * detune, seed + o * 977) * amp;
		norm += amp;
		amp *= 0.55f;
		freq *= 1.87f;
	}
	return norm > 0 ? sum / norm : 0;
}
int main(int argc, char **argv) {
	FILE *f = fopen(argc > 1 ? argv[1] : "sway_noise.luau", "w");
	if (!f) return 1;
	fprintf(f, "-- Generated by roblox/tools/golden/sway_noise.c. Do not edit.\nreturn {\nhash = {\n");
	const int seeds[] = { 101, 227, 353, 1901, 4801, 977, -5 };
	for (int s = 0; s < 7; s++)
		for (int i = -3; i < 2000; i += 37)
			fprintf(f, "{%d,%d,%.9g},\n", i, seeds[s], hash(i, seeds[s]));
	fprintf(f, "},\nfractal = {\n");
	for (int k = 0; k < 400; k++) {
		float x = (float)k * 0.173f;
		fprintf(f, "{%.9g,%.9g,%.9g,%.9g},\n", x, signed_noise(x, 4801), fractal(x, 101, 2, 0.35f), fractal(x, 1901, 2, 0.4f));
	}
	fprintf(f, "},\n}\n");
	fclose(f);
	return 0;
}
