// Golden trace generator for the Luau port (roblox/tests/golden/*.luau).
// Runs the original C++ code on scripted inputs and writes each frame's input
// and output as a Luau table. roblox/tests/golden.spec.luau replays the inputs
// through the Luau modules and compares.
//
// Build and run: roblox/tools/golden/build.sh
