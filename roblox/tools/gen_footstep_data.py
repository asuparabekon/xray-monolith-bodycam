#!/usr/bin/env python3
"""Generate src/Bodycam/Reference/FootstepCameraData.luau from the C++ data header.

Usage (from the repository root):
    python3 roblox/tools/gen_footstep_data.py
Reads src/xrGame/bodycam_reference/footstep_camera_data.h. Do not edit the output by hand.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/xrGame/bodycam_reference/footstep_camera_data.h"
OUTPUT = ROOT / "roblox/src/Bodycam/Reference/FootstepCameraData.luau"
NUMBER = r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?"


def constant(text, name):
    match = re.search(name + r"\s*=\s*(" + NUMBER + r")f?", text)
    if not match:
        raise SystemExit(f"constant {name} not found")
    return match.group(1)


def numbers(block):
    return [float(v) for v in re.findall(NUMBER + r"(?=f)", block)]


def fmt(values):
    return ", ".join(f"{v:.6f}" for v in values)


def main():
    text = SOURCE.read_text()
    bins = int(constant(text, "kFootstepCameraBins"))
    lunge_samples = int(constant(text, "kFootstepLungeSamples"))
    header = re.search(r"Source samples SHA256 ([0-9a-f]+)", text).group(1)

    cycles_block = text[text.index("FootstepCycles()"):text.index("FootstepSprintLunge()")]
    lunge_block = text[text.index("FootstepSprintLunge()"):]
    cycle_values = numbers(cycles_block)
    per_cycle = 3 * bins + 3
    if len(cycle_values) != 5 * per_cycle:
        raise SystemExit(f"unexpected cycle data size {len(cycle_values)}")
    lunge_values = numbers(lunge_block)
    if len(lunge_values) != 3 * lunge_samples:
        raise SystemExit(f"unexpected lunge data size {len(lunge_values)}")

    names = ["WalkForward", "WalkBackward", "WalkRight", "WalkLeft", "SprintForward"]
    out = [
        "-- Generated by roblox/tools/gen_footstep_data.py from",
        "-- src/xrGame/bodycam_reference/footstep_camera_data.h. Do not edit.",
        f"-- Source samples SHA256 {header}: Reference session head socket,",
        "-- camera-local metres (right, up, forward).",
        "",
        "local Data = {}",
        f"Data.BINS = {bins}",
        f"Data.LUNGE_SAMPLES = {lunge_samples}",
        f"Data.LUNGE_RATE = {constant(text, 'kFootstepLungeRate')}",
        f"Data.POSTURE_RATE = {constant(text, 'kFootstepPostureRate')}",
        f"Data.GAIT_RATE = {constant(text, 'kFootstepGaitRate')}",
        f"Data.WALK_SPEED = {constant(text, 'kFootstepWalkSpeed')}",
        f"Data.SPRINT_SPEED = {constant(text, 'kFootstepSprintSpeed')}",
        "-- Cycle order: " + ", ".join(names) + " (1-based in Luau).",
        "Data.CYCLES = {",
    ]
    for c, name in enumerate(names):
        chunk = cycle_values[c * per_cycle:(c + 1) * per_cycle]
        out.append(f"\t-- {name}")
        out.append("\t{")
        out.append("\t\taxes = {")
        for a in range(3):
            out.append("\t\t\t{ " + fmt(chunk[a * bins:(a + 1) * bins]) + " },")
        out.append("\t\t},")
        out.append("\t\tposture = { " + fmt(chunk[3 * bins:]) + " },")
        out.append("\t},")
    out.append("}")
    out.append("Data.SPRINT_LUNGE = {")
    for a in range(3):
        out.append("\t{ " + fmt(lunge_values[a * lunge_samples:(a + 1) * lunge_samples]) + " },")
    out.append("}")
    out.append("")
    out.append("return table.freeze(Data)")
    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
