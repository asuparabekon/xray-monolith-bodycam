-- Atlas reticle glow over deferred lens glass (the glow of scope_glass_fallback), and of a reflex in the capture,
-- added into $user$reticle_emission or the scene (svp_reticle_emission.cpp).
function normal(shader, t_base, t_second, t_detail)
	shader:begin("scope_vertex", "scope_glass_fallback_emission")
	: zb(false, false)
	: blend(true, blend.one, blend.one)
	: scopelense(3)
	shader:dx10texture("scope_reference_visible_glass", "$user$ssfx_motion_vectors")
	shader:dx10texture("s_reticle", "$user$reticle")
	shader:dx10texture("s_image", "$user$viewport2")
	shader:dx10texture("s_tonemap", "$user$tonemap")
	shader:dx10texture("s_tonemap_svp", "$user$svp_tonemap")
	shader:dx10texture("s_heat", "$user$heat")
	shader:dx10texture("s_distort", "$user$generic1")
	shader:dx10texture("s_position", "$user$generic2")
	shader:dx10texture("s_inside", "wpn\\scope_utility\\inside")
	shader:dx10texture("s_inside_blurred", "wpn\\scope_utility\\inside_blurred")
	shader:dx10texture("s_dirt", "wpn\\scope_utility\\dirt")
	shader:dx10texture("s_reflection", "wpn\\scope_utility\\reflection")
	shader:dx10texture("s_lens_env0", "$user$env_s0")
	shader:dx10texture("s_lens_env1", "$user$env_s1")
	shader:dx10texture("s_heat_map", "wpn\\scope_utility\\heat_map")
	shader:dx10texture("s_powered_off", "wpn\\eft_echo1\\eft_echo1_screen")
	shader:dx10texture("s_svp_rain", "fx\\svp_rain")
	shader:dx10texture("s_reticle_capture_emission", "$user$reticle_capture_emission")
	shader:dx10texture("s_reticle_capture_glow", "$user$reticle_capture_glow")
	shader:dx10sampler("smp_base")
	shader:dx10sampler("smp_rtlinear");
end
